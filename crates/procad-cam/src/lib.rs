//! Conservative CAM planning boundary.
//!
//! This crate validates evidence needed to prepare an external CAM handoff.
//! It deliberately does not generate machine toolpaths or communicate with
//! milling equipment. A generic CAD mesh export is not machine-ready data.

use serde::{Deserialize, Serialize};
use sha2::Digest;
use thiserror::Error;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CamEvidence {
    pub case_id: String,
    pub design_sha256: String,
    pub clinical_approval_id: String,
    pub clinical_approval_by: String,
    pub case_created_by: String,
    pub design_author_by: String,
    pub manufacturer_id: String,
    pub machine_model: String,
    pub machine_profile_id: String,
    pub machine_profile_verified: bool,
    pub material_id: String,
    pub blank_id: String,
    pub fixture_id: String,
    pub postprocessor_id: String,
    pub simulation_report_sha256: String,
    pub simulation_passed: bool,
    pub independent_qa_signoff_id: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CamJobStatus { PreparedForExternalReview, Blocked }

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CamJob {
    pub id: String,
    pub evidence: CamEvidence,
    pub status: CamJobStatus,
    pub dispatch_enabled: bool,
    pub warnings: Vec<String>,
}

#[derive(Debug, Error, PartialEq, Eq)]
pub enum CamGateError {
    #[error("missing required CAM evidence: {0}")]
    MissingEvidence(&'static str),
    #[error("clinical approval must be performed by a different user than the case creator")]
    MissingIndependentClinicalApproval,
    #[error("machine/material profile is not verified for this exact configuration")]
    UnverifiedMachineProfile,
    #[error("CAM simulation must pass and include a report checksum")]
    SimulationNotPassed,
    #[error("design or simulation checksum is invalid")]
    InvalidChecksum,
    #[error("physical machine dispatch is disabled in this build")]
    HardwareDispatchDisabled,
}

fn present(value: &str) -> bool { !value.trim().is_empty() }

fn valid_sha256(value: &str) -> bool {
    value.len() == 64 && value.bytes().all(|byte| byte.is_ascii_hexdigit())
}

/// Validates evidence and prepares an audit-ready record for a qualified CAM operator.
/// This does not produce a toolpath and is not a substitute for manufacturer CAM.
pub fn prepare_external_handoff(evidence: CamEvidence) -> Result<CamJob, CamGateError> {
    for (name, value) in [
        ("case_id", evidence.case_id.as_str()),
        ("case_created_by", evidence.case_created_by.as_str()),
        ("design_author_by", evidence.design_author_by.as_str()),
        ("clinical_approval_id", evidence.clinical_approval_id.as_str()),
        ("clinical_approval_by", evidence.clinical_approval_by.as_str()),
        ("manufacturer_id", evidence.manufacturer_id.as_str()),
        ("machine_model", evidence.machine_model.as_str()),
        ("machine_profile_id", evidence.machine_profile_id.as_str()),
        ("material_id", evidence.material_id.as_str()),
        ("blank_id", evidence.blank_id.as_str()),
        ("fixture_id", evidence.fixture_id.as_str()),
        ("postprocessor_id", evidence.postprocessor_id.as_str()),
        ("independent_qa_signoff_id", evidence.independent_qa_signoff_id.as_str()),
    ] {
        if !present(value) { return Err(CamGateError::MissingEvidence(name)); }
    }
    if evidence.clinical_approval_by == evidence.case_created_by
        || evidence.clinical_approval_by == evidence.design_author_by
    {
        return Err(CamGateError::MissingIndependentClinicalApproval);
    }
    if !valid_sha256(&evidence.design_sha256) || !valid_sha256(&evidence.simulation_report_sha256) {
        return Err(CamGateError::InvalidChecksum);
    }
    if !evidence.machine_profile_verified { return Err(CamGateError::UnverifiedMachineProfile); }
    if !evidence.simulation_passed { return Err(CamGateError::SimulationNotPassed); }

    let serialized = serde_json::to_vec(&evidence).map_err(|_| CamGateError::InvalidChecksum)?;
    let digest = sha2::Sha256::digest(serialized);
    Ok(CamJob {
        id: hex::encode(digest),
        evidence,
        status: CamJobStatus::PreparedForExternalReview,
        dispatch_enabled: false,
        warnings: vec![
            "No machine toolpath was generated by procad.".into(),
            "Transfer must be completed in the verified manufacturer's CAM software.".into(),
            "Confirm blank identity, orientation, fixtures, tools, postprocessor and simulation on the target machine.".into(),
            "This record does not establish clinical safety, fit or regulatory conformity.".into(),
        ],
    })
}

/// Physical transmission is intentionally unavailable; never silently fall back
/// to a raw serial/network write or direct machine-control protocol.
pub fn dispatch_to_machine(_job: &CamJob) -> Result<(), CamGateError> {
    Err(CamGateError::HardwareDispatchDisabled)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn approved_evidence() -> CamEvidence {
        CamEvidence {
            case_id: "case-123".into(),
            design_sha256: "a".repeat(64),
            clinical_approval_id: "approval-456".into(),
            clinical_approval_by: "clinician-b".into(),
            case_created_by: "clinician-a".into(),
            design_author_by: "clinician-a".into(),
            manufacturer_id: "manufacturer-x".into(),
            machine_model: "mill-y".into(),
            machine_profile_id: "profile-z".into(),
            machine_profile_verified: true,
            material_id: "material-1".into(),
            blank_id: "blank-1".into(),
            fixture_id: "fixture-1".into(),
            postprocessor_id: "post-1".into(),
            simulation_report_sha256: "b".repeat(64),
            simulation_passed: true,
            independent_qa_signoff_id: "qa-789".into(),
        }
    }

    #[test]
    fn prepares_auditable_external_handoff_only_with_full_evidence() {
        let job = prepare_external_handoff(approved_evidence()).unwrap();
        assert_eq!(job.status, CamJobStatus::PreparedForExternalReview);
        assert!(!job.dispatch_enabled);
        assert_eq!(job.id.len(), 64);
    }

    #[test]
    fn rejects_creator_or_design_author_approving_their_own_work() {
        let mut evidence = approved_evidence();
        evidence.clinical_approval_by = evidence.case_created_by.clone();
        assert_eq!(prepare_external_handoff(evidence.clone()), Err(CamGateError::MissingIndependentClinicalApproval));
        evidence.clinical_approval_by = "clinician-b".into();
        evidence.design_author_by = "clinician-b".into();
        assert_eq!(prepare_external_handoff(evidence), Err(CamGateError::MissingIndependentClinicalApproval));
    }

    #[test]
    fn refuses_unverified_machine_profiles() {
        let mut evidence = approved_evidence();
        evidence.machine_profile_verified = false;
        assert_eq!(prepare_external_handoff(evidence), Err(CamGateError::UnverifiedMachineProfile));
    }

    #[test]
    fn dispatch_is_disabled_even_for_a_complete_review_record() {
        let job = prepare_external_handoff(approved_evidence()).unwrap();
        assert_eq!(dispatch_to_machine(&job), Err(CamGateError::HardwareDispatchDisabled));
    }
}
